/** Patterns that prove a Live Grok narrative stole a flagship/sibling powertrain. */
const FLAGSHIP_ENGINE_RE =
  /\b(isl\s*8\.?9|isl\b|l9\s*450|x15|x12\s*500|1[,.]?250\s*lb|1250\s*lb|450\s*hp)\b/i;
const GAS_V10_RE =
  /\b(triton|v10|6\.8l\s*v10|ford\s*f-?53|torqshift|godzilla)\b/i;
const MID_DIESEL_RE = /\b(isb|b6\.7|b6\.7|340\s*hp|360\s*hp)\b/i;

export function findPowertrainCorrection(
  year: string | number,
  make: string,
  model: string,
  floorplan?: string,
): PowertrainCorrection | null {
  const y = typeof year === "number" ? year : parseInt(String(year), 10);
  if (!Number.isFinite(y)) return null;
  const mk = make.toLowerCase();
  const md = model.toLowerCase().replace(/\s+/g, " ").trim();
  const fp = (floorplan || "").toLowerCase();

  // Prefer floorplan-specific pins, then longer modelIncludes
  const hits = POWERTRAIN_CORRECTIONS.filter((c) => {
    if (y < c.yearMin || y > c.yearEnd) return false;
    if (!mk.includes(c.makeIncludes.toLowerCase())) return false;
    // Bare "newmar" must not stamp live-line pins onto Newmar Classic historic rows
    if (c.makeIncludes === "newmar" && mk.includes("classic")) return false;
    if (!md.includes(c.modelIncludes.toLowerCase())) return false;
    if (c.floorplanIncludes) {
      const cfp = c.floorplanIncludes.toLowerCase().replace(/[\s\-_/]/g, "");
      const nfp = fp.replace(/[\s\-_/]/g, "");
      // Exact after normalize — "35S" must not steal "35QS"
      if (!nfp || nfp !== cfp) return false;
    }
    // Avoid matching "discovery" rule on "discovery lxe" when a more specific exists
    if (c.modelIncludes === "discovery" && md.includes("discovery lxe")) {
      return false;
    }
    // Bare "ventana" must not stamp L9 400 onto Ventana LE
    if (c.modelIncludes === "ventana" && md.includes("ventana le")) {
      return false;
    }
    // Avoid matching bare "allegro red" on "allegro red 340/360"
    if (
      c.modelIncludes === "allegro red" &&
      (md.includes("allegro red 340") ||
        md.includes("allegro red 360") ||
        md.includes("allegro red340") ||
        md.includes("allegro red360"))
    ) {
      return false;
    }
    // Bare "wayfarer" must not stamp MY25+ 4500XD onto the Wayfarer 25 alias
    if (c.modelIncludes === "wayfarer" && /\bwayfarer\s*25\b/.test(md)) {
      return false;
    }
    // Bare "allegro" gas must not steal Bus / RED / Bay / Breeze
    if (
      c.modelIncludes === "allegro" &&
      (md.includes("allegro bus") ||
        md.includes("allegro red") ||
        md.includes("allegro bay") ||
        md.includes("allegro breeze"))
    ) {
      return false;
    }
    // Avoid matching bare "reatta" on "reatta xl" if needed later
    if (c.modelIncludes === "reatta" && md.includes("reatta xl")) {
      return false;
    }
    // Vision diesel trim / XL / SE are different products
    if (
      c.modelIncludes === "vision" &&
      (md.includes("vision xl") ||
        md.includes("vision se") ||
        md.includes("diesel"))
    ) {
      return false;
    }
    // Bare "accolade" ISB must not stamp Accolade XT Power Stroke
    if (c.modelIncludes === "accolade" && md.includes("accolade xt")) {
      return false;
    }
    // No OEM MY19–20 Accolade XL year page — do not inherit Accolade S2RV pin
    if (
      c.modelIncludes === "accolade" &&
      md.includes("accolade xl") &&
      y >= 2019 &&
      y <= 2020
    ) {
      return false;
    }
    // Bare "esteem" E-450 must not stamp Esteem XL Super C or Odyssey Esteem Edition
    if (
      c.modelIncludes === "esteem" &&
      (md.includes("esteem xl") || md.includes("odyssey esteem"))
    ) {
      return false;
    }
    // Bare "odyssey" E-450 must not stamp Odyssey SE chassis option-band
    if (
      c.modelIncludes === "odyssey" &&
      (md.includes("odyssey se") || md.includes("odyssey-se"))
    ) {
      return false;
    }
    // Bare "qwest" 25-series / 4500 must not stamp Qwest SE 24-series / 3500
    if (c.modelIncludes === "qwest" && md.includes("qwest se")) {
      return false;
    }
    // Bare "ethos" must not stamp Ethos Li lithium trim
    if (c.modelIncludes === "ethos" && md.includes("ethos li")) {
      return false;
    }
    // Bare "altitude" is E-450 Class C — not FS550 / FS600D Super C
    if (
      c.modelIncludes === "altitude" &&
      (md.includes("fs550") || md.includes("fs600"))
    ) {
      return false;
    }
    // Bare "frontier" must not stamp GTX
    if (c.modelIncludes === "frontier" && md.includes("frontier gtx")) {
      return false;
    }
    // Bare "bounder" must not stamp Bounder Classic
    if (c.modelIncludes === "bounder" && md.includes("bounder classic")) {
      return false;
    }
    // Bare "pace arrow" must not stamp Pace Arrow LXE
    if (c.modelIncludes === "pace arrow" && md.includes("pace arrow lxe")) {
      return false;
    }
    // Bare "discovery" must not stamp Discovery LXE
    if (c.modelIncludes === "discovery" && md.includes("discovery lxe")) {
      return false;
    }
    // Bare "flair" must not stamp Flair LXE
    if (c.modelIncludes === "flair" && md.includes("flair lxe")) {
      return false;
    }
    // Bare "seneca" ISB must not stamp Seneca XT Power Stroke
    if (c.modelIncludes === "seneca" && md.includes("seneca xt")) {
      return false;
    }
    // Bare "greyhawk" E-450 must not stamp Greyhawk XL Super C
    if (c.modelIncludes === "greyhawk" && md.includes("greyhawk xl")) {
      return false;
    }
    // Bare "redhawk" E-450 must not stamp Redhawk SE Ford/Chevy option-band
    if (c.modelIncludes === "redhawk" && md.includes("redhawk se")) {
      return false;
    }
    // Bare "melbourne" 3500 must not stamp Melbourne Prestige 3500/4500-by-year
    if (c.modelIncludes === "melbourne" && md.includes("melbourne prestige")) {
      return false;
    }
    // Bare "embark" pusher must not stamp Embark Super C (~2009–2012)
    if (c.modelIncludes === "embark" && md.includes("embark super")) {
      return false;
    }
    return true;
  }).sort((a, b) => {
    const af = a.floorplanIncludes ? 1 : 0;
    const bf = b.floorplanIncludes ? 1 : 0;
    if (bf !== af) return bf - af;
    return b.modelIncludes.length - a.modelIncludes.length;
  });

  return hits[0] ?? null;
}

/** True when Live Grok engine text conflicts with a brochure pin. */
export function powertrainConflictsWithPin(
  pin: PowertrainCorrection,
  engine: string | null | undefined,
  horsepower?: number | null,
): boolean {
  if (!engine) return false;
  const live = engine.toLowerCase();
  const pinned = pin.engine.toLowerCase();
  const pinIsMid =
    MID_DIESEL_RE.test(pinned) && !/isl|l9|x15|x12/.test(pinned);
  const liveIsFlagship =
    FLAGSHIP_ENGINE_RE.test(live) ||
    (horsepower != null &&
      pin.horsepower <= 380 &&
      horsepower >= 450);
  if (pinIsMid && liveIsFlagship) return true;
  if (
    /cummins|diesel|isb|b6/.test(pinned) &&
    GAS_V10_RE.test(live) &&
    !/cummins|isb|b6|l9|isl/.test(live)
  ) {
    return true;
  }
  if (
    pin.fuelType === "Gas" &&
    /cummins|diesel|isb|l9|isl/.test(live)
  ) {
    return true;
  }
  return false;
}

/**
 * Rewrite overview / feature chips that still name the wrong powertrain.
 * Keeps market/lifestyle language; strips sibling-engine claims.
 */
export function sanitizeNarrativeForPin(
  pin: PowertrainCorrection,
  text: string | null | undefined,
): string | null {
  if (!text) return text ?? null;
  let t = text;
  const eng = pin.engine;
  const hp = pin.horsepower;
  const tq = pin.torqueLbFt;

  // Replace common wrong powertrains with the pin label
  t = t.replace(
    /Cummins\s+ISL(?:\s*8\.?9L?)?(?:\s+\d+\s*HP)?(?:\s*\/\s*[\d,]+\s*lb-?ft)?/gi,
    eng,
  );
  t = t.replace(
    /Cummins\s+L9(?:\s+\d+\s*HP)?(?:\s*\/\s*[\d,]+\s*lb-?ft)?/gi,
    eng,
  );
  t = t.replace(
    /Ford\s+Triton\s+V10(?:\s*6\.8L)?(?:\s*\([^)]*\))?/gi,
    eng,
  );
  t = t.replace(/Ford\s+F-?53(?:\s+chassis)?/gi, pin.chassis || "chassis");
  if (hp > 0) {
    t = t.replace(/\b450\s*HP\b/gi, `${hp} HP`);
    t = t.replace(/\b320\s*HP\b/gi, `${hp} HP`);
  }
  if (tq && tq > 0) {
    t = t.replace(/\b1[,.]?250\s*lb-?ft\b/gi, `${tq.toLocaleString()} lb-ft`);
    t = t.replace(/\b832\s*lb-?ft\b/gi, `${tq.toLocaleString()} lb-ft`);
  }

  // Drop "early gas Red / gas F53" myths when pin is diesel RED
  if (pin.fuelType === "Diesel" || /cummins|isb|b6/i.test(pin.engine)) {
    t = t.replace(/\bearly\s+years?\s+gas\s+F-?53[^.]*\./gi, "");
    t = t.replace(/\bearly\s+gas\s+Red\b/gi, "diesel Allegro RED");
    t = t.replace(/\bgas\s+F-?53[^.]*\./gi, "");
    t = t.replace(/\b\(gas years\)/gi, "");
  }

  return t.replace(/\s{2,}/g, " ").trim() || null;
}

export function sanitizeFeaturesForPin(
  pin: PowertrainCorrection,
  features: string[] | null | undefined,
): string[] {
  if (!features?.length) return [];
  return features
    .map((f) => sanitizeNarrativeForPin(pin, f) || "")
    .filter(Boolean)
    .filter((f) => {
      // Drop chips that still scream wrong flagship after sanitize
      if (powertrainConflictsWithPin(pin, f)) return false;
      return true;
    })
    .slice(0, 8);
}
