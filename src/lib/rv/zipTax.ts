export function lookupTaxByZip(zip: string): ZipTaxInfo | null {
  const digits = zip.replace(/\D/g, "");
  if (digits.length < 3) return null;

  const prefix5 = digits.slice(0, 5);
  const prefix3 = digits.slice(0, 3);

  let row: ZipRow | undefined =
    (digits.length >= 5 ? ZIP_TO_STATE[prefix5] : undefined) ?? ZIP_TO_STATE[prefix3];

  let matched = ZIP_TO_STATE[prefix5] ? prefix5 : prefix3;

  if (!row) {
    const num = parseInt(prefix3, 10);
    if (Number.isFinite(num)) {
      for (const r of ZIP_RANGE_FALLBACK) {
        if (num >= r.min && num <= r.max) {
          row = { state: r.state, code: r.code, tax: r.tax, regBase: r.regBase };
          matched = `${r.min}-${r.max}`;
          break;
        }
      }
    }
  }

  if (!row) return null;

  return {
    state: row.state,
    abbr: row.code,
    taxRate: row.tax,
    registrationFees: Math.round(row.regBase * 2.2 + 80),
    zipPrefix: matched,
  };
}

export type ZipValidationStatus = "empty" | "incomplete" | "invalid" | "valid";

export type ZipValidation = {
  digits: string;
  zip5: string;
  status: ZipValidationStatus;
  info: ZipTaxInfo | null;
  message: string;
};

/** Digits only, first 5 then optional +4. */
export function formatZipInput(raw: string): string {
  const digits = raw.replace(/\D/g, "").slice(0, 9);
  if (digits.length <= 5) return digits;
  return `${digits.slice(0, 5)}-${digits.slice(5)}`;
}

/**
 * Require a complete 5-digit US ZIP before tax lookup.
 * ZIP+4 is accepted; tax uses the first five digits.
 */
export function validateUsZip(raw: string): ZipValidation {
  const digits = raw.replace(/\D/g, "").slice(0, 9);
  if (digits.length === 0) {
    return { digits, zip5: "", status: "empty", info: null, message: "" };
  }
  if (digits.length < 5) {
    const left = 5 - digits.length;
    return {
      digits,
      zip5: digits,
      status: "incomplete",
      info: null,
      message: `${left} more digit${left === 1 ? "" : "s"} needed for a US ZIP`,
    };
  }
  const zip5 = digits.slice(0, 5);
  const info = lookupTaxByZip(zip5);
  if (!info) {
    return {
      digits,
      zip5,
      status: "invalid",
      info: null,
      message: "Not a recognized US ZIP — check the number",
    };
  }
  const plus4 = digits.length > 5 ? `-${digits.slice(5)}` : "";
  const extra = digits.length > 5 && digits.length < 9 ? " · +4 incomplete" : "";
  return {
    digits,
    zip5,
    status: "valid",
    info,
    message: `${formatZipTaxLabel(info)}${plus4 ? ` · ${zip5}${plus4}` : ""}${extra}`,
  };
}

export function formatZipTaxLabel(info: ZipTaxInfo): string {
  return `${info.state} (${info.abbr}) — ${info.taxRate.toFixed(2)}% sales tax`;
}

export function zipTaxCoverage(): { prefixes: number; states: number } {
  const keys = Object.keys(ZIP_TO_STATE);
  const states = new Set(Object.values(ZIP_TO_STATE).map((r) => r.code));
  return { prefixes: keys.length, states: states.size };
}
