#!/usr/bin/env node
/**
 * Build the thin Facts wizard index from the live catalog.
 * Run after editing src/lib/rv/rvData.ts:
 *   node scripts/build-catalog-index.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadLiveCatalog } from "./load-live-catalog.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dest = resolve(root, "src/lib/rv/rvCatalogIndex.ts");

const { RV_DATA } = await loadLiveCatalog();

const index = {};
let models = 0;
for (const make of Object.keys(RV_DATA).sort((a, b) => a.localeCompare(b))) {
  const map = RV_DATA[make];
  if (!map) continue;
  index[make] = {};
  for (const model of Object.keys(map).sort((a, b) => a.localeCompare(b))) {
    const spec = map[model];
    if (!spec) continue;
    models += 1;
    const row = {
      type: spec.type,
      fuelType: spec.fuelType,
    };
    if (spec.yearStart != null) row.yearStart = spec.yearStart;
    if (spec.yearEnd != null) row.yearEnd = spec.yearEnd;
    if (spec.floorplansByYear && Object.keys(spec.floorplansByYear).length) {
      row.years = Object.keys(spec.floorplansByYear)
        .map((y) => parseInt(y, 10))
        .filter((n) => Number.isFinite(n))
        .sort((a, b) => a - b);
    }
    index[make][model] = row;
  }
}

const body = `/* AUTO-GENERATED by scripts/build-catalog-index.mjs — do not edit by hand.
 * Thin year / make / type / floorplan index for the Facts wizard.
 * Full specs stay in rvData.ts and load via ensureCatalogLoaded().
 */
import type { CatalogIndexSpec } from "./rvTypes";

export const CATALOG_INDEX: Record<string, Record<string, CatalogIndexSpec>> = ${JSON.stringify(index)};

export const MAKES = Object.keys(CATALOG_INDEX).sort((a, b) => a.localeCompare(b));
`;

writeFileSync(dest, body);
console.log(
  `Wrote ${dest} — ${Object.keys(index).length} makes, ${models} models, ${(body.length / 1024).toFixed(1)} KB`,
);
